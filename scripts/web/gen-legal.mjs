#!/usr/bin/env node
/**
 * One-off generator (Plan 2b Task 5): apps/admin/src/pages/{privacy-policy,terms-conditions,refund-policy}.tsx
 * -> packages/content/src/site/legal-data.ts, as GuideBlock[]. The words are moved unchanged (h2, p and li text,
 * <strong> as **bold**, links as [label](href)). Only two kinds of change, each listed in FIXES and in
 * 2b-review-CD.md: the terms page's live price list becomes one line, and rupee amounts become "as shown at
 * booking" wording (owner, 26 Nov: no prices on the new site). The script fails if a fix stops matching or a
 * rupee figure survives.
 *
 * Run: node scripts/web/gen-legal.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const SRC = new URL("../../apps/admin/src/pages/", import.meta.url);
const PAGES = { privacy: "privacy-policy.tsx", terms: "terms-conditions.tsx", refund: "refund-policy.tsx" };

export const FIXES = {
  terms: [
    ["{termsServices.map((row) => (\n                  <li key={row.id}>\n                    {row.title.trim()} - {formatINR(row.price)}\n                  </li>\n                ))}",
     "<li>Current prices are shown at booking.</li>", "live price list (Plan 2b: no exact-price component on the new site)"],
    ["A booking fee of ₹299 (₹499 for paint protection film services priced above ₹10,000) is required to secure your appointment.",
     "A booking fee, as shown at booking, is required to secure your appointment.", "rupee amounts (owner, 26 Nov)"],
  ],
  refund: [
    ["charges a booking fee of ₹299 (₹499 for paint protection film services priced above ₹10,000) to secure your appointment.",
     "charges a booking fee, as shown at booking, to secure your appointment.", "rupee amounts (owner, 26 Nov)"],
    ["Full refund of the booking fee (₹299, or ₹499 for paint protection film services priced above ₹10,000)",
     "Full refund of the booking fee", "rupee amounts"],
    ["50% refund (₹149.50)", "50% refund of the booking fee", "rupee amount"],
    ["No refund (₹0)", "No refund", "rupee amount"],
    ["Premium Car Wash Special (₹999)", "Premium Car Wash Special", "old exact price in heading"],
    ["Interior Detailing (₹4,000)", "Interior Detailing", "old exact price in heading"],
    ["Exterior Detailing (₹3,500)", "Exterior Detailing", "old exact price in heading"],
    ["Windshield Glass Coating (₹1,699)", "Windshield Glass Coating", "old exact price in heading"],
    ["Headlight Restoration (₹1,499)", "Headlight Restoration", "old exact price in heading"],
  ],
  privacy: [],
};

function inner(s) {
  return s
    .replace(/\{"\s*"\}/g, " ")
    .replace(/<strong[^>]*>([\s\S]*?)<\/strong>/g, "**$1**")
    .replace(/<b>([\s\S]*?)<\/b>/g, "**$1**")
    .replace(/<a[^>]*href="([^"]+)"[^>]*>([\s\S]*?)<\/a>/g, (_m, h, t) => `[${t.trim()}](${h})`)
    .replace(/<[^>]+>/g, "")
    .replace(/\s+/g, " ")
    .replace(/\s+([,.;:])/g, "$1")
    .trim();
}

const out = {};
for (const [key, file] of Object.entries(PAGES)) {
  let src = readFileSync(new URL(file, SRC), "utf8").replace(/\r\n/g, "\n");
  for (const [from, to] of FIXES[key]) {
    if (!src.includes(from)) throw new Error(`${key}: fix no longer matches: ${from.slice(0, 80)}`);
    src = src.split(from).join(to);
  }
  src = src.replace(/\{\/\*[\s\S]*?\*\/\}/g, "");
  const body = src.slice(src.indexOf("</h1>") + 5);
  const blocks = [];
  for (const m of body.matchAll(/<(h2|h3|p|li)\b[^>]*>([\s\S]*?)<\/\1>/g)) {
    const text = inner(m[2]);
    if (!text || /^Last updated|^©/.test(text)) continue;
    if (/[{}]/.test(text)) throw new Error(`${key}: unresolved expression: ${text}`);
    if (/₹\s?\d/.test(text)) throw new Error(`${key}: rupee figure survives: ${text}`);
    if (m[1] === "li") {
      const last = blocks[blocks.length - 1];
      if (last && last.t === "ul") last.items.push(text); else blocks.push({ t: "ul", items: [text] });
    } else blocks.push(m[1] === "p" ? { t: "p", text } : { t: m[1], text });
  }
  out[key] = blocks;
}

writeFileSync(new URL("../../packages/content/src/site/legal-data.ts", import.meta.url), `/**
 * GENERATED by scripts/web/gen-legal.mjs from apps/admin/src/pages/{privacy-policy,terms-conditions,refund-policy}.tsx.
 * Do not edit by hand. Wording unchanged except the FIXES listed in that script.
 */
import type { GuideBlock } from "./types.ts";

export const LEGAL_BLOCKS: Record<"privacy" | "terms" | "refund", GuideBlock[]> = ${JSON.stringify(out, null, 2)};
`);
console.log(Object.entries(out).map(([k, v]) => `${k}: ${v.length} blocks`).join(", "));
